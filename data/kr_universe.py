def get_forced_kr_universe_at(snapshot_date: str) -> list[str]:
    """
    특정 날짜 기준으로 한국 유니버스에 포함 가능한 종목 반환.
    added_date > snapshot_date 종목 제외 (사후편입 편향 방지).
    """
    from datetime import date as _date
    try:
        snap_d = _date.fromisoformat(snapshot_date)
    except Exception:
        return list(FORCED_KR_UNIVERSE.keys())

    result = []
    for code in FORCED_KR_UNIVERSE:
        meta = FORCED_KR_META.get(code)
        if meta is None:
            result.append(code)
            continue
        try:
            if _date.fromisoformat(meta["added_date"]) <= snap_d:
                result.append(code)
        except Exception:
            result.append(code)
    return result


